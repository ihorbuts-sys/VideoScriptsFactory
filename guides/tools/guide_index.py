#!/usr/bin/env python3
"""Writes GUIDE_INDEX.md: every active guide by shot type with its level, camera, length, trigger, move, objects,
swap family and the script steps that use it, plus the pending guides. The script composer reads it to reuse guides.

    python3 guides/tools/guide_index.py
"""
import glob
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
# Guides that share one object builder: swapping the object (another cup, another dish, another glass) changes the
# whole family, so a new object variant starts from the family's template guide (objects audit, 2026-11-10).
FAMILIES = {
    "cup": ("steam_orbit_eye", ["steam_low_backlit", "steam_push_in_high", "steam_orbit_eye", "steam_slide_pull_out",
             "handoff_counter_cup", "counter_edge_to_pass", "counter_over_shoulder", "counter_through_cup_handle",
             "pour_top_down_latte", "pour_side_low", "pour_upside_down", "room_reveal_cup", "room_seated_pan",
             "sip_selfie_eye", "sip_high_lean", "sip_friend_side"]),
    "dish": ("plate_high_orbit", ["plate_low_push_in", "plate_high_orbit", "plate_tissue_slide", "handoff_plate_lands",
              "verdict_high_plate", "bite_selfie_eye", "bite_friend_three_quarter"]),
    "glass": ("glass_slide_close", ["glass_slide_close", "table_spread_orbit", "pancake_clear_path"]),
}


def objects(setup):
    match = re.search(r"\*\*Objects\*\*:(.*?)(\n- \*\*|\Z)", setup or "", re.S)
    text = " ".join(match.group(1).split()) if match else ""
    return text[:110] + ("..." if len(text) > 110 else "")


def main():
    plan = json.loads((ROOT / "guides/p0/plan.json").read_text())
    levels = json.loads((ROOT / "guides/p0/guide_levels.json").read_text())
    used = {}
    for path in sorted(glob.glob(str(ROOT / "scripts/_parts/*.json"))):
        for template in json.loads(Path(path).read_text())["templates"]:
            for step in template["steps"]:
                for gid in step.get("guides", []):
                    used.setdefault(gid, []).append(f"{template['id']}.{step['id']}")
    family_of = {g: (name, template) for name, (template, members) in FAMILIES.items() for g in members}
    lines = ["# Guide index", "",
             "Generated by `guides/tools/guide_index.py` from `guides/p0/plan.json`, `guides/p0/guide_levels.json` and",
             "`scripts/_parts`. Do not edit by hand. Level rule: " + levels["rule"], "",
             "A step reuses a guide when the shot type and level match; the first guide of a step is the recommended one.",
             "A new object on an existing move starts from its family's template (Swap column); see `skills/guide-objects`.", ""]
    by_type = {}
    for guide in plan["guides"]:
        by_type.setdefault(guide["shotType"], []).append(guide)
    for shot_type in [t["id"] for t in plan["shotTypes"]]:
        lines += [f"## {shot_type}", "",
                  "| Guide | Title | Level | Camera | Orientation | s | Trigger | Move | Objects | Swap | Used by |",
                  "|---|---|---|---|---|---|---|---|---|---|---|"]
        for g in by_type.get(shot_type, []):
            level = levels["guides"].get(g["id"], {})
            family = family_of.get(g["id"])
            swap = (f"{family[0]} (template {family[1]})" if family else "-")
            orientation = "upside down" if g["id"] in levels.get("orientation", {}).get("portraitUpsideDown", []) else "portrait"
            lines.append(f"| {g['id']} | {g['title']} | {level.get('complexity', '?')} | {g['camera']} | {orientation} | {g['durationSec']} | "
                         f"{g['startTrigger']} | {g['technique']} | {objects(g.get('sourceSetup'))} | {swap} | "
                         f"{', '.join(used.get(g['id'], [])) or '-'} |")
        lines.append("")
    lines += ["## Pending guides", "", "| Guide | Shot type | Level | Camera | s | For steps | Spec |", "|---|---|---|---|---|---|---|"]
    for p in levels.get("pending", []):
        lines.append(f"| {p['id']} | {p['shotType']} | {p['complexity']} | {p['camera']} | {p['durationSec']} | "
                     f"{', '.join(p.get('steps', []))} | {p['spec'][:140]}... |")
    (ROOT / "GUIDE_INDEX.md").write_text("\n".join(lines) + "\n")
    print(f"GUIDE_INDEX.md: {len(plan['guides'])} guides, {len(levels.get('pending', []))} pending")


if __name__ == "__main__":
    main()
